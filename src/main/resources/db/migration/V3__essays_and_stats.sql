-- 3단계: 자기소개서 버전 관리 + 통계

-- 실수로 바로 되돌린 상태 변경 표시 (통계에서 제외). 기존 행은 false.
alter table status_history add column reverted boolean default false not null;

create table essay_questions (
    id            bigint generated by default as identity primary key,
    posting_id    bigint not null,
    question      varchar(1000) not null,
    max_length    integer,
    category      varchar(20) not null,
    display_order integer not null,
    created_at    timestamp(6) with time zone not null,
    constraint fk_question_posting foreign key (posting_id) references job_posting (id),
    constraint ck_question_category check (category in ('MOTIVATION', 'GROWTH', 'COMPETENCY', 'COLLABORATION', 'OTHER'))
);

-- 답변 버전: append-only. (question_id, version) 유니크가 동시 저장 시 번호 중복을 DB 수준에서 막는다.
-- source_template_id 는 템플릿이 지워져도 출처가 남도록 FK 를 두지 않는다.
create table essay_answers (
    id                 bigint generated by default as identity primary key,
    question_id        bigint not null,
    version            integer not null,
    content            varchar(20000) not null,
    char_count         integer not null,
    submitted          boolean not null,
    source_template_id bigint,
    created_at         timestamp(6) with time zone not null,
    constraint uk_answer_question_version unique (question_id, version),
    constraint fk_answer_question foreign key (question_id) references essay_questions (id)
);

-- 임시저장: 문항당 1행 덮어쓰기 (버전 목록과 분리)
create table essay_drafts (
    question_id bigint primary key,
    content     varchar(20000) not null,
    updated_at  timestamp(6) with time zone not null,
    constraint fk_draft_question foreign key (question_id) references essay_questions (id)
);

create table answer_templates (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null,
    category   varchar(20) not null,
    title      varchar(200) not null,
    content    varchar(20000) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint fk_template_user foreign key (user_id) references users (id),
    constraint ck_template_category check (category in ('MOTIVATION', 'GROWTH', 'COMPETENCY', 'COLLABORATION', 'OTHER'))
);

-- 통계 집계("도달 여부")와 목록 조회용 인덱스
create index idx_history_application_status on status_history (application_id, to_status);
create index idx_posting_user on job_posting (user_id);
create index idx_question_posting on essay_questions (posting_id);
create index idx_template_user_category on answer_templates (user_id, category);
