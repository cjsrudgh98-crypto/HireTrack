-- 1단계: 회원, 공고, 지원(공고와 1:1), 상태 변경 이력
-- PostgreSQL 과 H2(PostgreSQL 모드, 로컬·테스트용)에서 모두 동작하는 SQL 만 쓴다.

create table users (
    id         bigint generated by default as identity primary key,
    email      varchar(255) not null,
    password   varchar(255) not null,
    created_at timestamp(6) with time zone not null,
    constraint uk_users_email unique (email)
);

create table job_posting (
    id              bigint generated by default as identity primary key,
    user_id         bigint not null,
    company         varchar(100) not null,
    title           varchar(200) not null,
    url             varchar(500),
    location        varchar(100),
    employment_type varchar(20),
    deadline        date,
    requirements    varchar(5000),
    created_at      timestamp(6) with time zone not null,
    updated_at      timestamp(6) with time zone not null,
    constraint fk_posting_user foreign key (user_id) references users (id),
    constraint ck_posting_employment_type check (employment_type in ('FULL_TIME', 'FREELANCE', 'OTHER'))
);

create table application (
    id         bigint generated by default as identity primary key,
    posting_id bigint not null,
    status     varchar(20) not null,
    applied_at timestamp(6) with time zone,
    memo       varchar(10000),
    constraint uk_application_posting unique (posting_id),
    constraint fk_application_posting foreign key (posting_id) references job_posting (id),
    constraint ck_application_status check (status in ('INTERESTED', 'APPLIED', 'DOCUMENT_PASSED', 'INTERVIEW', 'ACCEPTED', 'REJECTED'))
);

create table status_history (
    id             bigint generated by default as identity primary key,
    application_id bigint not null,
    from_status    varchar(20),
    to_status      varchar(20) not null,
    changed_at     timestamp(6) with time zone not null,
    constraint fk_history_application foreign key (application_id) references application (id),
    constraint ck_history_from check (from_status in ('INTERESTED', 'APPLIED', 'DOCUMENT_PASSED', 'INTERVIEW', 'ACCEPTED', 'REJECTED')),
    constraint ck_history_to check (to_status in ('INTERESTED', 'APPLIED', 'DOCUMENT_PASSED', 'INTERVIEW', 'ACCEPTED', 'REJECTED'))
);
