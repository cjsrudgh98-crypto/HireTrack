-- 4단계: 면접 일정 + 캘린더 구독 피드

create table interviews (
    id               bigint generated by default as identity primary key,
    posting_id       bigint not null,
    type             varchar(20) not null,
    starts_at        timestamp(6) with time zone not null,
    duration_minutes integer not null,
    location         varchar(200),
    memo             varchar(2000),
    created_at       timestamp(6) with time zone not null,
    updated_at       timestamp(6) with time zone not null,
    constraint fk_interview_posting foreign key (posting_id) references job_posting (id),
    constraint ck_interview_type check (type in ('FIRST', 'SECOND', 'EXECUTIVE', 'CODING_TEST', 'ASSIGNMENT'))
);

create index idx_interview_posting on interviews (posting_id);
create index idx_interview_starts_at on interviews (starts_at);

-- 캘린더 앱이 인증 헤더 없이 읽는 구독 URL 의 비밀 토큰 (재발급 시 교체)
create table calendar_feeds (
    user_id    bigint primary key,
    token      varchar(64) not null,
    created_at timestamp(6) with time zone not null,
    constraint uk_calendar_token unique (token),
    constraint fk_calendar_user foreign key (user_id) references users (id)
);
