-- 2단계: 마감 임박 알림 설정과 발송 기록

create table notification_settings (
    user_id       bigint primary key,
    email_enabled boolean not null,
    remind_days   varchar(20) not null,  -- 예: '3,1'
    send_hour     integer not null,
    constraint fk_notification_settings_user foreign key (user_id) references users (id),
    constraint ck_notification_send_hour check (send_hour between 0 and 23)
);

-- (posting_id, remind_day) 유니크: 스케줄러가 두 번 돌거나 여러 서버에서 동시에 돌아도 같은 알림은 한 번만 기록·발송된다.
-- 공고를 지우면 기록도 앱에서 함께 지우므로 FK 는 두지 않는다.
create table notification_logs (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null,
    posting_id bigint not null,
    remind_day integer not null,
    sent_at    timestamp(6) with time zone not null,
    constraint uk_notification_posting_day unique (posting_id, remind_day)
);
